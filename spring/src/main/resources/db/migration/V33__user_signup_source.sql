-- V33: 가입한 사람이 애초에 어디서 들어왔는지
--
--   V32 가 댓글에 넣은 source 와 같은 값이고 같은 쿠키(jw_src)에서 온다.
--   담기는 것은 분류된 소스 이름 하나뿐이다(google, naver, sns:x, internal, direct, other).
--   원본 Referer URL 도, 새 식별자도 만들지 않는다.
--
--   다만 댓글의 source 와 성격이 다르다는 것을 적어 둔다. 댓글은 익명 한 건에 붙는 값이라
--   사람과 이어지지 않지만, 계정의 source 는 지속되는 신원에 붙어 아이디·별명과 함께
--   한 사람을 가리킨다. 그래서 가입 화면에 이 사실을 적어 두었다.
--
--   이 기능이 생기기 전에 가입한 계정은 null 로 남고 화면에서 unknown 으로 묶인다.
--   되살릴 수 없다 -- 원본 Referer 를 애초에 저장하지 않았기 때문이다.
-- ============================================================

alter table public.tb_user
    add column if not exists source text;
